// Writes the migration that moves the Hyrule map's collectibles to the
// game's own positions (compare-collectibles.cjs's matches), and its undo.
//
//   node dev/assets/oot/collectibles-to-sql.cjs markers.json maps.json <migration name>
//
// Each marker keeps its ID, name and text (completions and bookmarks are by
// ID), and changes only while it's still where it was: a marker someone has
// moved by hand since is left alone. Its game data records which game record
// it is (gameId, gameRecord), so later imports can find it. A dungeon marker
// on the wrong floor moves to the right floor's submap too.
const fs = require('fs');
const path = require('path');
const {compare} = require('./compare-collectibles.cjs');

const RECORD = {'Gold Skulltula': 'MapParam.CollectSign', 'Heart Piece': 'MapParam.CollectHeart', 'Big Poe': 'Actor.Enemy_Poe_Big'};
const [markersFile, mapsFile, name] = process.argv.slice(2);
if(!markersFile || !mapsFile || !name) throw new Error('Usage: node collectibles-to-sql.cjs markers.json maps.json <migration name>');

const read = file => JSON.parse(fs.readFileSync(file, 'utf8'));
const {matches} = compare(read(markersFile), read(mapsFile));
// Dungeon floor changes: the submap is set too, and checked like the position.
const moving = m => m.targetSubmapId && m.targetSubmapId !== m.submapId;
const submapTo = m => moving(m) ? `submap_id = ${m.targetSubmapId}, ` : '';
const submapIs = (m, id) => moving(m) ? ` AND submap_id = ${id}` : '';
const submapBack = m => moving(m) ? `submap_id = ${m.submapId}, ` : '';
const num = value => Number(value).toFixed(3).replace(/\.?0+$/, '');
const at = (x, y) => `ABS(x - ${num(x)}) < 0.0005 AND ABS(y - ${num(y)}) < 0.0005`;
const sorted = matches.slice().sort((a, b) => Number(a.markerId) - Number(b.markerId));

const up = [
  '-- Moves OoT\'s Heart Pieces, Gold Skulltulas and Big Poes (Hyrule and the',
  '-- dungeons) to the',
  '-- game\'s own positions, converted exactly from game coordinates (see',
  '-- dev/assets/oot/game-to-map.cjs). Generated by collectibles-to-sql.cjs.',
  '-- IDs, names and text stay, so completions and bookmarks are unaffected; a',
  '-- marker is only moved while it is still where it was.',
  '',
  // The name goes on its own line: bin/migrate.php splits statements on a
  // ';' that ends a line.
  ...sorted.map(m => `-- ${m.name.replace(/[\r\n]/g, ' ')}: ${m.offsetPixels}px\n` +
    `UPDATE marker SET ${submapTo(m)}x = ${num(m.game[0])}, y = ${num(m.game[1])}, last_updated = NOW(),` +
    ` game_data = JSON_SET(COALESCE(game_data, '{}'), '$.gameId', '${m.sourceId}', '$.gameRecord', '${RECORD[m.category]}')` +
    ` WHERE id = ${m.markerId} AND ${at(...m.ours)}${submapIs(m, m.submapId)};`)
];
const down = [
  '-- Puts the Hyrule map\'s collectibles back where they were, if they are',
  '-- still at the positions the migration gave them.',
  '',
  ...sorted.map(m => `UPDATE marker SET ${submapBack(m)}x = ${num(m.ours[0])}, y = ${num(m.ours[1])},` +
    ` game_data = JSON_REMOVE(game_data, '$.gameId', '$.gameRecord')` +
    ` WHERE id = ${m.markerId} AND ${at(...m.game)}${submapIs(m, m.targetSubmapId)};`)
];
const folder = path.join(__dirname, '..', '..', '..', 'migrations');
fs.writeFileSync(path.join(folder, name + '.sql'), up.join('\n') + '\n');
fs.writeFileSync(path.join(folder, name + '.down.sql'), down.join('\n') + '\n');
console.log(`${sorted.length} markers -> migrations/${name}.sql`);
