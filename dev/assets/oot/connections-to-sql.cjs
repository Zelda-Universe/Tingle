// Writes the migration that puts the Hyrule map's connector ends on the
// game's own exits (compare-connections.cjs), and its undo.
//
//   node dev/assets/oot/connections-to-sql.cjs hyrule-links.json <migration name>
//
// hyrule-links.json must hold each submap's connections exactly as stored
// (the "raw" text): the migration only changes a submap whose connections
// are still that text, so a later edit is never overwritten. Ends with no
// game exit keep their position.
const fs = require('fs');
const path = require('path');
const {compare} = require('./compare-connections.cjs');

const [linksFile, name] = process.argv.slice(2);
if(!linksFile || !name) throw new Error('Usage: node connections-to-sql.cjs hyrule-links.json <migration name>');
const links = JSON.parse(fs.readFileSync(linksFile, 'utf8'));
const result = compare(links);
const quote = text => "'" + text.replace(/\\/g, '\\\\').replace(/'/g, "''") + "'";

const up = ['-- Puts the Hyrule map\'s connector ends on the game\'s own exits (its', '-- EntranceAnchors), converted exactly to the map. Generated by', '-- dev/assets/oot/connections-to-sql.cjs. A submap changes only while its', '-- connections are still as they were.', ''];
const down = ['-- Puts the Hyrule map\'s connector ends back where they were.', ''];
for(const [submapId, {updated}] of Object.entries(result)) {
  const before = links[submapId].raw, after = JSON.stringify(updated);
  up.push(`UPDATE submap SET connections = ${quote(after)} WHERE id = ${submapId} AND connections = ${quote(before)};`);
  down.push(`UPDATE submap SET connections = ${quote(before)} WHERE id = ${submapId} AND connections = ${quote(after)};`);
}
const folder = path.join(__dirname, '..', '..', '..', 'migrations');
fs.writeFileSync(path.join(folder, name + '.sql'), up.join('\n') + '\n');
fs.writeFileSync(path.join(folder, name + '.down.sql'), down.join('\n') + '\n');
console.log('migrations/' + name + '.sql');
