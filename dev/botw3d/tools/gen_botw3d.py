#!/usr/bin/env python3
"""Writes the migration for BotW's 3D Divine Beast maps (admin-only for now):
the map, its version, and its markers from the Beast's map units.

python3 gen_botw3d.py <objs.json> <actor-names.json> <migrations dir>
objs.json: the Beast's map unit objects (byml.py on its *_Static/*_Dynamic.smubin);
actor-names.json: ActorType names from Bootup_USen.pack (msbt.py).
"""
import json, os, sys
OBJS, NAMES, OUT = sys.argv[1:4]
objs, names = json.load(open(OBJS)), json.load(open(NAMES))
NAME = '20261118100000_botw_vah_ruta_3d'
MAP, SUB, FIRST = 1951, 195101, 19510001
USER = 'COALESCE((SELECT id FROM user WHERE id = 15), 1)'
q = lambda s: "'" + str(s).replace("\\", "\\\\").replace("'", "''") + "'"
GEAR = ('Weapon_', 'Obj_FireArrow', 'Obj_IceArrow', 'Obj_ElectricArrow', 'Obj_BombArrow', 'Obj_AncientArrow', 'Armor_')
up = [f"""-- Breath of the Wild: Divine Beast Vah Ruta as a 3D map, for staff only
-- (map.visible = 2) while it's built. Its model and textures are the game's
-- own (images/3d/botw/vah-ruta/), converted by dev/botw3d/tools; markers are
-- its chests, terminals, travel gate and Guardian Scouts from its map units,
-- at their game coordinates (x, y across; z up). Generated by gen_botw3d.py.
-- Harmless to run again.
""",
f"INSERT INTO map (id, container_id, name, is_default, default_zoom, max_zoom, map_copyright, map_order, visible, kind) SELECT {MAP}, 19, 'Vah Ruta', 0, 1, 6, 'Model &#169; Nintendo.', 100, 2, '3d' FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM map WHERE id = {MAP});",
f"INSERT INTO submap (id, map_id, map_type_id, mapper_id, name, is_default, tile_url, tile_ext, img404, submap_order, empty_map, opacity, visible, tile_version, bounds) SELECT {SUB}, {MAP}, 1, NULL, 'Vah Ruta', 1, 'images/3d/botw/vah-ruta/', 'glb', 'blank', 1, 0, 1, 1, NULL, NULL FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM submap WHERE id = {SUB});"]
n = 0
for o in objs:
    u = o['UnitConfigName']; x, height, y = o['Translate']
    drop = (o.get('!Parameters') or {}).get('DropActor')
    if u.startswith('TBox'):
        cat, name = (1944 if drop and drop.startswith(GEAR) else 1943), names.get(drop, drop or 'Treasure Chest')
    elif u == 'DgnObj_RemainsTerminalBody_A': cat, name = 1926, 'Terminal'
    elif u == 'DgnObj_RemainsDownloadTerminalBody_A': cat, name = 1926, 'Main Control Unit'
    elif u == 'DgnObj_WarpPoint_Remains': cat, name = 1926, 'Travel Gate'
    elif u.startswith('Enemy_Guardian_Mini'): cat, name = 1932, names.get(u, 'Guardian Scout')
    else: continue
    mid = FIRST + n; n += 1
    up.append(f"-- {u}" + (f" ({drop})" if drop else ''))
    up.append(f"INSERT INTO marker (id, submap_id, overlay_id, marker_status_id, marker_category_id, user_id, name, description, x, y, z, jump_marker_id, global, path, game_data, visible, last_updated) SELECT {mid}, {SUB}, NULL, 2, {cat}, {USER}, {q(name)}, '', {round(x, 3)}, {round(y, 3)}, {round(height, 3)}, 0, 0, '', NULL, 1, NOW() FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM marker WHERE id = {mid});")
open(os.path.join(OUT, NAME + '.sql'), 'w').write('\n'.join(up) + '\n')
open(os.path.join(OUT, NAME + '.down.sql'), 'w').write(f"""-- Removes what {NAME} added.
DELETE FROM marker WHERE id BETWEEN {FIRST} AND {FIRST + 999};
DELETE FROM submap WHERE id = {SUB};
DELETE FROM map WHERE id = {MAP} AND container_id = 19;
""")
print(n, 'markers')
