<?php
// One-off: writes the migration that copies Ocarina of Time from its
// read-only pack (data/OoT) into the database, keeping every ID, so
// bookmarks, completions and shared links keep working.
//
//   php dev/assets/oot/pack-to-sql.php
//
// It reads the pack through ootPackData(), the same reader the site uses,
// so the database gets exactly what the site serves today: submap names
// without "State 00", tile versions, maps in play order.
//
// The game goes in hidden (container.visible = 0): every list of games, the
// sitemap and the SEO pages only show visible ones, so nothing changes until
// the site is switched over to read OoT from here.

$root = dirname(__DIR__, 3);
require $root . '/lib/common/oot_pack.php';

const OOT_GAME = 64;
const OOT_SHORT_NAME = 'OoTR';   // the old N64 entry already has 'OoT'
const AUTHOR = 1;                // as BotW's labels; the pack credits no account
const APPROVED = 2;              // marker_status and marker_tab_status

// A MySQL string literal. bin/migrate.php splits statements on a ';' that
// ends a line, so each statement stays on one line: line breaks are escaped.
function sql($value) {
  if ($value === null) return 'NULL';
  if (is_bool($value)) return $value ? '1' : '0';
  if (is_int($value)) return (string) $value;
  // Every digit: (string) on a float keeps only 14 significant ones.
  if (is_float($value)) return json_encode($value);
  return "'" . strtr((string) $value, ["\\" => "\\\\", "'" => "''", "\n" => "\\n", "\r" => "\\r"]) . "'";
}
// Marker names and tab text are stored HTML-encoded, as add_marker.php does.
function encoded($text) {
  return htmlentities((string) $text, ENT_QUOTES, 'UTF-8');
}
// A row with its ID, skipped if that ID is already there. Not INSERT IGNORE:
// that also turns every other error into a silent warning, and so cut "webp"
// to "web" in a three-letter column without a word.
// For a table with unique keys besides its ID (container's short_name): adds
// the row only if its ID is missing, and fails loudly on any other clash.
function insertIfMissing($table, array $row) {
  return 'INSERT INTO ' . $table . ' (' . implode(', ', array_keys($row)) . ') SELECT ' .
    implode(', ', array_map('sql', array_values($row))) . ' FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM ' . $table .
    ' WHERE id = ' . (int) $row['id'] . ');';
}
function insert($table, array $row) {
  return 'INSERT INTO ' . $table . ' (' . implode(', ', array_keys($row)) . ') VALUES (' .
    implode(', ', array_map('sql', array_values($row))) . ') ON DUPLICATE KEY UPDATE id = id;';
}

$container = ootPackData('container')[0];
$maps = ootPackData('maps');
$categories = ootPackData('categories');
$markers = ootPackData('markers');

$lines = [
  '-- Ocarina of Time, copied from its read-only pack (data/OoT) into the',
  '-- database with all its IDs. Generated by dev/assets/oot/pack-to-sql.php,',
  '-- do not edit by hand. Safe to run twice: rows already there are skipped',
  '-- (by ID; tabs only for markers that have none). Anything that doesn\'t fit',
  '-- its column fails the migration rather than being cut short.',
  '-- The game is hidden until the site reads OoT from the database.',
  '',
  '-- An empty placeholder game called OoTR (staging had one, as 23) would take',
  '-- the short name: names are unique, ignoring case. Remove it only if it has',
  '-- no maps or categories; one with content stops the next statement instead.',
  "DELETE FROM container WHERE LOWER(short_name) = 'ootr' AND id <> " . OOT_GAME .
    ' AND NOT EXISTS (SELECT 1 FROM map m WHERE m.container_id = container.id)' .
    ' AND NOT EXISTS (SELECT 1 FROM marker_category c WHERE c.container_id = container.id);',
  '',
  '-- The game, if its ID is free. Not ON DUPLICATE KEY: that also matches the',
  '-- unique short name, and skipped this row silently while OoTR was taken.',
  insertIfMissing('container', [
    'id' => OOT_GAME, 'short_name' => OOT_SHORT_NAME, 'name' => $container['name'],
    'marker_url' => $container['markerURL'], 'marker_ext' => $container['markerExt'],
    'background_color' => $container['bgColor'], 'icon' => $container['icon'],
    'show_street_view' => 0, 'show_map_control' => (int) $container['showMapControl'],
    'show_zoom_control' => (int) $container['showZoomControl'], 'show_pan_control' => 0, 'show_category_menu' => 1,
    'default_pos_x' => (float) $container['centerX'], 'default_pos_y' => (float) $container['centerY'],
    'bound_top_pos_x' => (float) $container['boundTopX'], 'bound_top_pos_y' => (float) $container['boundTopY'],
    'bound_bottom_pos_x' => (float) $container['boundBottomX'], 'bound_bottom_pos_y' => (float) $container['boundBottomY'],
    'max_zoom' => (int) $container['maxZoom'], 'cluster_max_zoom' => (int) $container['clusterMaxZoom'],
    'cluster_grid_size' => (int) $container['clusterGridSize'], 'tile_size' => (int) $container['tileSize'],
    'icon_width' => (int) $container['iconWidth'], 'icon_height' => (int) $container['iconHeight'],
    'icon_small_width' => (int) $container['iconSmallWidth'], 'icon_small_height' => (int) $container['iconSmallHeight'],
    'switch_icons_at_zoom' => (int) $container['switchIconsAtZoom'],
    'scaleP' => (float) $container['scaleP'], 'scaleN' => (float) $container['scaleN'],
    'offsetX' => (float) $container['offsetX'], 'offsetY' => (float) $container['offsetY'],
    'visible' => 0, 'enabled' => 1, 'default_zoom' => (int) $container['defaultZoom'],
  ]),
  '',
  '-- Its categories: Collectibles, then Heart Pieces, Gold Skulltulas, Big Poes.',
];
// Parents first: a category's parent must exist before it does.
usort($categories, fn($a, $b) => ($a['parent_id'] === null ? 0 : 1) <=> ($b['parent_id'] === null ? 0 : 1));
foreach ($categories as $category) {
  $lines[] = insert('marker_category', [
    'id' => (int) $category['id'], 'parent_id' => $category['parent_id'] === null ? null : (int) $category['parent_id'],
    'marker_category_type_id' => (int) $category['marker_category_type_id'], 'container_id' => OOT_GAME,
    'name' => $category['name'], 'default_checked' => (bool) $category['default_checked'],
    'img' => $category['img'], 'color' => $category['color'],
    'visible_zoom' => (int) $category['visible_zoom'], 'visible' => (bool) $category['visible'],
  ]);
}

$lines[] = '';
$lines[] = '-- Its maps (Hyrule, then the dungeons in play order) and their submaps:';
$lines[] = "-- Hyrule's ages, the dungeons' floors and water levels.";
foreach ($maps as $order => $map) {
  $lines[] = insert('map', [
    'id' => (int) $map['id'], 'container_id' => OOT_GAME, 'name' => $map['name'],
    'is_default' => $order === 0, 'default_zoom' => (int) $map['defaultZoom'], 'max_zoom' => (int) $map['maxZoom'],
    'map_copyright' => 'Map artwork © Nintendo.', 'map_order' => $order + 1, 'visible' => 1, 'kind' => $map['kind'],
  ]);
  foreach ($map['subMap'] as $submapOrder => $submap) {
    $lines[] = insert('submap', [
      'id' => (int) $submap['id'], 'map_id' => (int) $map['id'], 'map_type_id' => 1, 'mapper_id' => null,
      'name' => trim($submap['name']), 'is_default' => (bool) (int) $submap['isDefault'],
      'tile_url' => $submap['tileURL'], 'tile_ext' => $submap['tileExt'], 'img404' => $submap['img404'],
      'submap_order' => $submapOrder + 1, 'empty_map' => (bool) (int) $submap['emptyMap'],
      'opacity' => (float) $submap['opacity'], 'visible' => 1,
      'tile_version' => $submap['tileVersion'],
      'bounds' => empty($submap['bounds']) ? null : json_encode($submap['bounds']),
      'connections' => empty($submap['connections']) ? null : json_encode($submap['connections'], JSON_UNESCAPED_UNICODE),
    ]);
  }
}

$lines[] = '';
$lines[] = '-- Its markers, with their IDs (641xxxxx Heart Pieces, 642xxxxx Gold';
$lines[] = '-- Skulltulas, 643xxxxx Big Poes), and each one\'s how-to text as its tab.';
foreach ($markers as $marker) {
  $lines[] = insert('marker', [
    'id' => (int) $marker['id'], 'submap_id' => (int) $marker['submapId'], 'overlay_id' => null,
    'marker_status_id' => APPROVED, 'marker_category_id' => (int) $marker['markerCategoryId'], 'user_id' => AUTHOR,
    'name' => encoded($marker['name']), 'description' => encoded($marker['description']),
    'x' => (float) $marker['x'], 'y' => (float) $marker['y'], 'z' => $marker['z'] === null ? null : (float) $marker['z'],
    'jump_marker_id' => 0, 'global' => (int) $marker['globalMarker'], 'path' => (string) $marker['path'],
    'game_data' => $marker['gameData'], 'visible' => 1,
  ]);
}
foreach ($markers as $marker) {
  if ((string) $marker['tabText'] === '') continue;
  $id = (int) $marker['id'];
  $lines[] = 'INSERT INTO marker_tab (marker_id, marker_tab_status_id, user_id, tab_title, tab_text, tab_order, visible) ' .
    'SELECT ' . implode(', ', [$id, APPROVED, AUTHOR, sql(encoded($marker['tabTitle'])), sql(encoded($marker['tabText'])), 1, 1]) .
    ' FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM marker_tab WHERE marker_id = ' . $id . ');';
}

// Hyrule's place names, as BotW's and TotK's are: label markers in an "Area
// Labels" category, and each place's border as a map_region area. Each age
// has its own (the same 20 places, Hyrule Castle becoming Ganon's Castle).
// Labels get IDs in their own block, 6440xxxx for Child and 6441xxxx for
// Adult, so running this again skips them.
const LABELS = 64010, AREA_LABELS = 64011;
$lines[] = '';
$lines[] = "-- Hyrule's place names: label markers (\"Area Labels\", as BotW and TotK)";
$lines[] = '-- and their borders as map_region areas. Lon Lon Ranch has no border of';
$lines[] = '-- its own (it is inside Hyrule Field); its markers name it in game_data.';
$lines[] = insert('marker_category', [
  'id' => LABELS, 'parent_id' => null, 'marker_category_type_id' => 3, 'container_id' => OOT_GAME,
  'name' => 'Labels', 'default_checked' => true, 'img' => 'General_Map', 'color' => '#cdb269',
  'visible_zoom' => 0, 'visible' => true,
]);
$lines[] = insert('marker_category', [
  'id' => AREA_LABELS, 'parent_id' => LABELS, 'marker_category_type_id' => 3, 'container_id' => OOT_GAME,
  'name' => 'Area Labels', 'default_checked' => true, 'img' => '', 'color' => '',
  'visible_zoom' => 0, 'visible' => true,
]);
$labelCount = 0; $borderCount = 0;
foreach ($maps as $map) {
  foreach ($map['subMap'] as $ageIndex => $submap) {
    foreach (array_values($submap['placeLabels'] ?? []) as $index => $place) {
      $lines[] = insert('marker', [
        'id' => 64400001 + $ageIndex * 10000 + $index, 'submap_id' => (int) $submap['id'], 'overlay_id' => null,
        'marker_status_id' => APPROVED, 'marker_category_id' => AREA_LABELS, 'user_id' => AUTHOR,
        'name' => encoded($place['name']), 'description' => '', 'x' => (float) $place['x'], 'y' => (float) $place['y'],
        'z' => null, 'jump_marker_id' => 0, 'global' => 0, 'path' => '',
        'game_data' => json_encode(['source' => 'OoT place label']), 'visible' => 1,
      ]);
      $labelCount++;
      if (empty($place['bounds'])) continue;
      // [[south, west], [north, east]] as a closed GeoJSON ring of [x, y].
      [[$south, $west], [$north, $east]] = $place['bounds'];
      $ring = [[$west, $south], [$east, $south], [$east, $north], [$west, $north], [$west, $south]];
      $lines[] = 'INSERT INTO map_region (submap_id, name, short_name, kind, region_order, polygon) VALUES (' .
        implode(', ', [(int) $submap['id'], sql($place['name']), sql($place['name']), sql('area'), $index,
          sql(json_encode(['type' => 'MultiPolygon', 'coordinates' => [[$ring]]]))]) .
        ') ON DUPLICATE KEY UPDATE id = id;';
      $borderCount++;
    }
  }
}

$file = $root . '/migrations/20261106070000_oot_into_database.sql';
file_put_contents($file, implode("\n", $lines) . "\n");
file_put_contents($root . '/migrations/20261106070000_oot_into_database.down.sql', implode("\n", [
  '-- Removes the OoT rows the migration added (children first, for the foreign',
  '-- keys). Completions and bookmarks keep their IDs and are untouched.',
  "DELETE FROM map_region WHERE kind = 'area' AND submap_id IN (SELECT s.id FROM submap s JOIN map m ON m.id = s.map_id WHERE m.container_id = " . OOT_GAME . ');',
  'DELETE FROM marker_tab WHERE marker_id BETWEEN 64100000 AND 64499999;',
  'DELETE FROM marker WHERE id BETWEEN 64100000 AND 64499999;',
  'DELETE FROM submap WHERE map_id IN (SELECT id FROM map WHERE container_id = ' . OOT_GAME . ');',
  'DELETE FROM map WHERE container_id = ' . OOT_GAME . ';',
  'DELETE FROM marker_category WHERE container_id = ' . OOT_GAME . ' AND parent_id IS NOT NULL;',
  'DELETE FROM marker_category WHERE container_id = ' . OOT_GAME . ';',
  'DELETE FROM container WHERE id = ' . OOT_GAME . ';',
  '',
]));
printf("%s: %d KB\n1 game, %d categories, %d maps, %d submaps, %d markers, %d place labels, %d borders\n", basename($file),
  filesize($file) / 1024, count($categories) + 2, count($maps), array_sum(array_map(fn($m) => count($m['subMap']), $maps)), count($markers),
  $labelCount, $borderCount);
