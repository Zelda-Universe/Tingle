#!/usr/bin/env python3
"""Writes The Minish Cap's maps, places and items migrations from
build_rom_maps.py's spec.json.

python3 gen_tmc_rom.py <spec.json> <migrations dir> [extras.json]
The categories (20261117110000) and admin-only (20261117130000) migrations
don't depend on the art and are left as they are.
"""
import json, os, sys

spec = json.load(open(sys.argv[1])); OUT = sys.argv[2]
extras = json.load(open(sys.argv[3])) if len(sys.argv) > 3 else []
C = 12
USER = 'COALESCE((SELECT id FROM user WHERE id = 15), 1)'
COPY = 'Map artwork &#169; Nintendo.'

def q(s):
    return "'" + str(s).replace("\\", "\\\\").replace("'", "''") + "'"
def html_escape(text):
    """Stored as the site stores tab text: HTML, itself escaped."""
    return text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace('"', '&quot;').replace("'", '&#39;')
def write(name, up, down):
    open(os.path.join(OUT, name + '.sql'), 'w').write(up.rstrip() + '\n')
    open(os.path.join(OUT, name + '.down.sql'), 'w').write(down.rstrip() + '\n')
# No game_data: the marker page shows a marker's text only without it (it's
# BotW's own detail lists, ZMap's content). Where each marker comes from is in
# the comment line above it.
def marker_sql(mid, submap, cat, name, x, y, data):
    return (f"INSERT INTO marker (id, submap_id, overlay_id, marker_status_id, marker_category_id, user_id, name, description, x, y, z, jump_marker_id, global, path, game_data, visible, last_updated) "
            f"SELECT {mid}, {submap}, NULL, 2, {cat}, {USER}, {q(name)}, '', {x}, {y}, NULL, 0, 0, '', NULL, 1, NOW() FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM marker WHERE id = {mid});")
def cat_sql(cid, parent, name, img, color, ctype):
    return (f"INSERT INTO marker_category (id, parent_id, marker_category_type_id, container_id, name, default_checked, img, color, visible_zoom, visible) "
            f"SELECT {cid}, {'NULL' if parent is None else parent}, {ctype}, {C}, {q(name)}, 1, {q(img)}, {q(color)}, 0, 1 FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM marker_category WHERE id = {cid});")

# --- Maps -----------------------------------------------------------------------
up = ["""-- The Minish Cap (GBA): the game's maps, rendered from the game itself:
-- every room drawn with MCEdit's mclib from a US cartridge dump and laid
-- out where the game places it (zeldaret/tmc's room tables). Hyrule is the
-- game's own world; Cloud Tops' three layers and each dungeon's floors are
-- versions of one map; every other area (Minish places, caves, houses) is a
-- map of its own. Tiles in tiles/tmc/v1/, written by build_rom_maps.py; this
-- file by gen_tmc_rom.py. Harmless to run again.
""", f"UPDATE container SET default_zoom = 2, max_zoom = 6, icon = 'Minish-Cap' WHERE id = {C};"]
for order, m in enumerate(spec['maps']):
    kind = 'NULL' if m['kind'] is None else q(m['kind'])
    up.append(f"-- {m['name']}")
    up.append(f"INSERT INTO map (id, container_id, name, is_default, default_zoom, max_zoom, map_copyright, map_order, visible, kind) SELECT {m['id']}, {C}, {q(m['name'])}, {1 if order == 0 else 0}, {min(2, m['native'])}, {m['native']}, {q(COPY)}, {order}, 1, {kind} FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM map WHERE id = {m['id']});")
    for i, s in enumerate(m['submaps'], 1):
        bounds = json.dumps(s['bounds']).replace(' ', '')
        up.append(f"INSERT INTO submap (id, map_id, map_type_id, mapper_id, name, is_default, tile_url, tile_ext, img404, submap_order, empty_map, opacity, visible, tile_version, bounds) SELECT {s['id']}, {m['id']}, 1, NULL, {q(s['name'])}, {1 if s['default'] else 0}, {q('tmc/v1/' + s['folder'] + '/')}, 'webp', 'blank', {i}, 0, 1, 1, {q(s['version'])}, {q(bounds)} FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM submap WHERE id = {s['id']});")
write('20261117100000_tmc_maps', '\n'.join(up), f"""-- Removes what 20261117100000_tmc_maps added.
DELETE FROM submap WHERE map_id BETWEEN 1200 AND 1299;
DELETE FROM map WHERE id BETWEEN 1200 AND 1299 AND container_id = {C};
UPDATE container SET default_zoom = 3, max_zoom = 6, icon = '' WHERE id = {C};""")

# --- Places: Hyrule's areas and the dungeon entrances ------------------------------
HYRULE = spec['maps'][0]['submaps'][0]['id']
up = ["""-- The Minish Cap: Hyrule's areas as borders with labels, outlined from the
-- game's own rooms (each area, and each part of Hyrule Field, is a room of
-- its own); and the game's places, people and events from the zeldaret/tmc
-- decompilation (tmc_extras.py): the doors out of Hyrule (houses, shops,
-- caves, fairy fountains, minigames, dungeons; src/data/transitions.c),
-- Kinstone Fusion results and golden enemies (src/gameData.c gWorldEvents),
-- and from the rooms' entity lists elements, heart containers, Great
-- Fairies, Wind Crests, Minish Portals, named NPCs, Business Scrubs, shop
-- stock and bosses. Generated by gen_tmc_rom.py. Harmless to run again.
""", cat_sql(12090, None, 'Labels', 'General_Map', '#cdb269', 3), cat_sql(12091, 12090, 'Area Labels', '', '', 3)]
for i, r in enumerate(spec['regions']):
    mid = 12005001 + i
    geo = json.dumps({'type': 'MultiPolygon', 'coordinates': [[ring] for ring in r['rings']]}, separators=(',', ':'))
    up.append(f"-- {r['name']}")
    up.append(marker_sql(mid, HYRULE, 12091, r['name'], r['label'][0], r['label'][1], {'source': 'TMC place label'}))
    up.append(f"INSERT IGNORE INTO map_region (submap_id, name, short_name, kind, region_order, polygon, connection_key, label_marker_id) VALUES ({HYRULE}, {q(r['name'])}, {q(r['name'])}, 'area', {i}, {q(geo)}, {q(r['name'])}, {mid});")
for i, e in enumerate(spec['entrances']):
    up.append(f"-- {e['name']} (entrance)")
    up.append(marker_sql(12003001 + i, HYRULE, 12051, e['name'], e['mx'], e['my'], {'source': 'TMC dungeon entrance'}))
for n, e in enumerate(sorted(extras, key=lambda e: (e['cat'], e['submap'], e['my'], e['mx']))):
    up.append(f"-- {e['name']}: " + ', '.join(f'{k} {v}' for k, v in e['data'].items() if k not in ('source', 'text')))
    mid = 12030001 + n
    text = e['data'].pop('text', None)
    up.append(marker_sql(mid, e['submap'], e['cat'], e['name'], e['mx'], e['my'], e['data']))
    if text:  # a sign's words, as the game shows them
        html = '&lt;p&gt;' + '&lt;br&gt;'.join(html_escape(line) for line in text.split('\n')) + '&lt;/p&gt;'
        up.append(f"INSERT INTO marker_tab (marker_id, marker_tab_status_id, user_id, tab_title, tab_text, tab_order, visible) SELECT {mid}, 2, {USER}, '', {q(html)}, 1, 1 FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM marker_tab WHERE marker_id = {mid});")
write('20261117120000_tmc_places', '\n'.join(up), f"""-- Removes what 20261117120000_tmc_places added.
DELETE FROM marker_tab WHERE marker_id BETWEEN 12030001 AND 12099999;
DELETE FROM marker WHERE id BETWEEN 12030001 AND 12099999;
DELETE FROM map_region WHERE submap_id = {HYRULE} AND kind = 'area' AND label_marker_id BETWEEN 12005001 AND 12005099;
DELETE FROM marker WHERE id BETWEEN 12005001 AND 12005099;
DELETE FROM marker WHERE id BETWEEN 12003001 AND 12003099;
DELETE FROM marker_category WHERE id = 12091 AND NOT EXISTS (SELECT 1 FROM marker WHERE marker_category_id = 12091);
DELETE FROM marker_category WHERE id = 12090 AND NOT EXISTS (SELECT 1 FROM marker_category WHERE parent_id = 12090);""")

# --- Items ------------------------------------------------------------------------
ITEMS = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'tmc_item_names.json')))
WHERE = {'chest': 'In a chest.', 'big chest': 'In a big chest.', 'ground': 'Lying on the floor.'}
items = sorted(spec['items'], key=lambda i: (i['submap'], i['my'], i['mx']))
missing = sorted({i['itemName'] for i in items if i['itemName'] not in ITEMS})
if missing: sys.exit('No name or category for: ' + ', '.join(missing))
FIRST = 12010001
up = ["""-- The Minish Cap: chests and the items lying in the open, on every map.
-- Contents and positions from the zeldaret/tmc decompilation's room data
-- (data/map/entity_headers.s, include/item.h), US release, at their rooms'
-- places in the rendered maps. Loose rupees and kinstones are left out
-- (drops from trees, pots and events), as are chests that appear after a
-- Kinstone Fusion or an event (set up in the game's code, not its room
-- data). Generated by gen_tmc_rom.py. Harmless to run again.
"""]
for n, it in enumerate(items):
    mid = FIRST + n
    name, cat = ITEMS[it['itemName']]
    if it['itemName'] == 'ITEM_SHELLS' and it['amount']: name = f"{it['amount']} Mysterious Shells"
    data = {'source': 'zeldaret/tmc', 'room': it['room'], 'how': it['how'], 'item': it['itemName']}
    up.append(f"-- {it['room']}: {name} ({it['how']}, {it['itemName']})")
    up.append(marker_sql(mid, it['submap'], cat, name, it['mx'], it['my'], data))
    up.append(f"INSERT INTO marker_tab (marker_id, marker_tab_status_id, user_id, tab_title, tab_text, tab_order, visible) SELECT {mid}, 2, {USER}, '', {q('&lt;p&gt;' + WHERE[it['how']] + '&lt;/p&gt;')}, 1, 1 FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM marker_tab WHERE marker_id = {mid});")
write('20261117140000_tmc_items', '\n'.join(up), """-- Removes what 20261117140000_tmc_items added.
DELETE FROM marker_tab WHERE marker_id BETWEEN 12010001 AND 12019999;
DELETE FROM marker WHERE id BETWEEN 12010001 AND 12019999;""")
print(len(spec['maps']), 'maps;', len(spec['regions']), 'areas;', len(items), 'items')
